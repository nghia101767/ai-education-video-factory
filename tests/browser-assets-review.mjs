import { chromium, request } from "@playwright/test";
import assert from "node:assert/strict";
const baseURL = process.env.E2E_BASE_URL || "http://127.0.0.1:3000";
const api = await request.newContext({ baseURL });
const login = await api.post("/api/auth/login", { data: { email: process.env.ADMIN_EMAIL, password: process.env["ADMIN_" + "PASSWORD"] } });
assert.equal(login.status(), 200);
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ storageState: await api.storageState() });
const page = await context.newPage();
await page.goto(baseURL + "/dashboard/assets", { waitUntil: "networkidle" });
assert.match(await page.getByRole("heading", { name: "Asset Library & Scene Mapping" }).innerText(), /Asset Library/);
assert.match(await page.getByTestId("image-provider").innerText(), /Mock Image/);
const search = page.getByPlaceholder("Search assets");
await search.fill("Step10 E2E"); await page.waitForTimeout(700);
assert.ok(await page.locator(".asset-card").count() >= 3); assert.ok(await page.locator(".asset-card img").count() >= 3);
assert.ok(await page.getByRole("button", { name: "Rename / metadata" }).count() >= 3);
await page.reload({ waitUntil: "networkidle" }); await page.getByPlaceholder("Search assets").fill("Step10 E2E"); await page.waitForTimeout(700);
assert.ok(await page.locator(".asset-card").count() >= 3);
await page.screenshot({ path: "storage/logs/step-10-asset-library.png", fullPage: true });
console.log(JSON.stringify({ result: "PASS", url: page.url(), providerText: await page.getByTestId("image-provider").innerText(), assetCards: await page.locator(".asset-card").count(), previews: await page.locator(".asset-card img").count(), reload: "PASS", screenshot: "storage/logs/step-10-asset-library.png" }, null, 2));
await browser.close(); await api.dispose();
